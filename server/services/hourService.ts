/**
 * @file Volunteer hours (FR-18, FR-19): a person's own log across every org, manual entries,
 * and the review queue. Nobody may approve their own hours.
 */
import { HourStatus } from '@shared/enums';
import { AppError } from '@shared/errors';
import * as rules from '@shared/rules';
import { hourLogSchema } from '@shared/schemas';
import { buildIndexes, toSessionView, toVolunteer } from '@shared/domain/views';
import type { DataSnapshot } from '@shared/domain/snapshot';
import type { HourLog, User } from '@shared/types';
import { enforce, found, fullName, newId, orgOfSession, requireOrg, validate } from './context';

/** An hour log joined for display. */
export type HourRow = HourLog & {
  volunteer: ReturnType<typeof toVolunteer>;
  session?: ReturnType<typeof toSessionView>;
  orgName: string;
};

/**
 * Joins hour logs with their person, session and org.
 * @param data - Snapshot.
 * @param logs - Logs.
 * @returns Rows, newest first.
 */
function toHourRows(data: DataSnapshot, logs: HourLog[]): HourRow[] {
  const idx = buildIndexes(data);
  return logs
    .map((h) => {
      const session = h.sessionId ? idx.sessions.get(h.sessionId) : undefined;
      return {
        ...h,
        orgName: idx.orgs.get(h.orgId)?.name ?? '',
        volunteer: toVolunteer(idx, h.orgId, h.userId),
        session: session ? toSessionView(data, session, idx) : undefined,
      };
    })
    .sort((a, b) => b.date.localeCompare(a.date));
}

/**
 * The signed-in person's hours across every org.
 * @param data - Snapshot.
 * @param me - Signed-in person.
 * @returns Hour rows.
 */
export function myHours(data: DataSnapshot, me: User): HourRow[] {
  return toHourRows(
    data,
    data.hourLogs.filter((h) => h.userId === me.id),
  );
}

/**
 * An org's hour logs for review (FR-19).
 * @param data - Snapshot.
 * @param me - Signed-in person.
 * @param orgId - Org.
 * @param query - Optional status / person filters.
 * @returns Hour rows.
 */
export function listHours(
  data: DataSnapshot,
  me: User,
  orgId: string,
  query: { status?: HourStatus; userId?: string } = {},
): HourRow[] {
  requireOrg(data, me, orgId, 'hours.review');
  return toHourRows(
    data,
    data.hourLogs.filter(
      (h) =>
        h.orgId === orgId &&
        (!query.status || h.status === query.status) &&
        (!query.userId || h.userId === query.userId),
    ),
  );
}

/**
 * Logs hours manually for one org (FR-18). They start PENDING.
 * @param draft - Draft snapshot.
 * @param me - Signed-in person.
 * @param input - Raw hour log.
 * @returns The log.
 */
export function createHourLog(draft: DataSnapshot, me: User, input: unknown): HourLog {
  const data = validate(hourLogSchema, input);
  found(
    draft.organizations.find((o) => o.id === data.orgId),
    'organization',
  );
  const session = data.sessionId ? draft.sessions.find((s) => s.id === data.sessionId) : undefined;
  if (data.sessionId && !session) found(session, 'session');
  if (session && orgOfSession(draft, session.id) !== data.orgId)
    throw new AppError(
      'VALIDATION',
      'That session belongs to a different organization.',
      'sessionId',
    );
  enforce(
    rules.hoursPlausible(data.hours, data.date, session), // V-S6
    rules.dailyHoursCap(
      data.hours,
      data.date,
      draft.hourLogs.filter((h) => h.userId === me.id),
    ), // V-S7
  );
  const log: HourLog = {
    id: newId('hl'),
    userId: me.id,
    orgId: data.orgId,
    sessionId: data.sessionId || undefined,
    date: data.date,
    hours: data.hours,
    description: data.description,
    status: HourStatus.PENDING,
    autoGenerated: false,
  };
  draft.hourLogs.push(log);
  return log;
}

/**
 * Approves or rejects an hour log (FR-19).
 * @param draft - Draft snapshot.
 * @param me - Signed-in person.
 * @param id - Hour log.
 * @param status - APPROVED or REJECTED.
 * @param note - Optional note to the volunteer.
 * @returns The log.
 */
export function reviewHours(
  draft: DataSnapshot,
  me: User,
  id: string,
  status: unknown,
  note?: unknown,
): HourLog {
  const log = found(
    draft.hourLogs.find((h) => h.id === id),
    'hour log',
  );
  requireOrg(draft, me, log.orgId, 'hours.review');
  if (status !== HourStatus.APPROVED && status !== HourStatus.REJECTED)
    throw new AppError('VALIDATION', 'Choose approve or reject.', 'status');
  if (note !== undefined && note !== null && typeof note !== 'string')
    throw new AppError('VALIDATION', 'The note must be text.', 'note');
  if (log.userId === me.id)
    throw new AppError(
      'FORBIDDEN',
      "You can't approve your own hours. Another leader in this organization needs to review them.",
    );
  if (note && note.length > 200)
    throw new AppError('VALIDATION', 'Keep the note under 200 characters.', 'note');
  log.status = status;
  log.reviewedBy = fullName(me);
  log.reviewNote = (note as string | undefined)?.trim() || undefined;
  return log;
}
